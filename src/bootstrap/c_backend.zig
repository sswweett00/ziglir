fn scanCapabilities(module: *const IRModule) struct { has_net: bool, has_threads: bool, fn_addr_taken: [ir.MAX_FNS]bool } {
    var has_net = false;
    var has_threads = false;
    var fn_addr_taken: [ir.MAX_FNS]bool = .{false} ** ir.MAX_FNS;
    for (module.fns[0..module.fn_count]) |*f| {
        for (f.blocks[0..f.block_count]) |*b| {
            for (b.insts[0..b.inst_count]) |inst| {
                if (inst.op == .fn_addr and inst.callee_fn_idx >= 0 and @as(usize, @intCast(inst.callee_fn_idx)) < ir.MAX_FNS) {
                    fn_addr_taken[@intCast(inst.callee_fn_idx)] = true;
                }
                switch (inst.op) {
                    .call_tcp_socket, .call_tcp_listen, .call_tcp_accept, .call_tcp_connect, .call_sock_send, .call_sock_recv => has_net = true,
                    .call_thread_create, .call_thread_join, .call_mutex_create, .call_mutex_lock, .call_mutex_unlock, .call_chan_new, .call_chan_send, .call_chan_recv, .call_chan_close => has_threads = true,
                    else => {},
                }
            }
        }
    }
    return .{ .has_net = has_net, .has_threads = has_threads, .fn_addr_taken = fn_addr_taken };
}

fn emitEdgePhis(w: anytype, f: *const IRFn, from_blk: u16, to_blk: u16) !void {
    const dest_b = &f.blocks[to_blk];
    var phi_n: u16 = 0;
    while (phi_n < dest_b.inst_count and dest_b.insts[phi_n].op == .phi) : (phi_n += 1) {
        const p = dest_b.insts[phi_n];
        var src_v: u16 = 0;
        for (0..p.arg_count) |ai| {
            if (p.phi_blocks[ai] == from_blk) {
                src_v = p.args[ai];
                break;
            }
        }
        try w.print("    uint64_t _pt_{d}_{d} = v{d};\n", .{ to_blk, phi_n, src_v });
    }
    var k: u16 = 0;
    while (k < phi_n) : (k += 1) {
        const p = dest_b.insts[k];
        if (p.dest != 0) try w.print("    v{d} = _pt_{d}_{d};\n", .{ p.dest, to_blk, k });
    }
}

