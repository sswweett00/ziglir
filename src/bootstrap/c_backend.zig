                    .call_time_ns => try w.print("    v{d} = lir_time_ns();\n", .{inst.dest}),
                    .call_open => try w.print("    v{d} = (uint64_t)lir_open(v{d}, (int64_t)v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1], if (inst.arg_count >= 3) inst.args[2] else 0 }),
                    .call_read => try w.print("    v{d} = (uint64_t)lir_read_fd((int64_t)v{d}, v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1], inst.args[2] }),
                    .call_write => try w.print("    v{d} = (uint64_t)lir_write_fd((int64_t)v{d}, v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1], inst.args[2] }),
                    .call_close => try w.print("    v{d} = (uint64_t)lir_close_fd((int64_t)v{d});\n", .{ inst.dest, inst.args[0] }),
                    .call_unlink => try w.print("    v{d} = (uint64_t)lir_unlink_p(v{d});\n", .{ inst.dest, inst.args[0] }),
                    .call_mkdir => try w.print("    v{d} = (uint64_t)lir_mkdir_p(v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1] }),
                    .call_stat => if (inst.arg_count >= 2)
                        try w.print("    v{d} = (uint64_t)lir_stat_buf(v{d}, v{d});\n", .{ inst.dest, inst.args[0], inst.args[1] })
                    else
                        try w.print("    v{d} = (uint64_t)lir_stat_p(v{d});\n", .{ inst.dest, inst.args[0] }),
                    .call_getpid => try w.print("#if defined(_WIN32)\n    v{d} = (uint64_t)_getpid();\n#elif defined(__wasi__)\n    v{d} = 1ULL;\n#else\n    v{d} = (uint64_t)getpid();\n#endif\n", .{ inst.dest, inst.dest, inst.dest }),
                    .call_getppid => try w.print("#if defined(_WIN32) || defined(__wasi__)\n    v{d} = 1ULL;\n#else\n    v{d} = (uint64_t)getppid();\n#endif\n", .{ inst.dest, inst.dest }),
                    .call_getuid => try w.print("#if defined(_WIN32) || defined(__wasi__)\n    v{d} = 0ULL;\n#else\n    v{d} = (uint64_t)getuid();\n#endif\n", .{ inst.dest, inst.dest }),
                    .call_tcp_socket => try w.print("    v{d} = (uint64_t)lir_tcp_socket();\n", .{inst.dest}),
                    .call_tcp_listen => try w.print("    v{d} = (uint64_t)lir_tcp_listen((int64_t)v{d}, (int64_t)v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1], inst.args[2] }),
                    .call_tcp_accept => try w.print("    v{d} = (uint64_t)lir_tcp_accept((int64_t)v{d});\n", .{ inst.dest, inst.args[0] }),
                    .call_tcp_connect => try w.print("    v{d} = (uint64_t)lir_tcp_connect((int64_t)v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1] }),
                    .call_sock_send => try w.print("    v{d} = (uint64_t)lir_sock_send((int64_t)v{d}, v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1], inst.args[2] }),
                    .call_sock_recv => try w.print("    v{d} = (uint64_t)lir_sock_recv((int64_t)v{d}, v{d}, (int64_t)v{d});\n", .{ inst.dest, inst.args[0], inst.args[1], inst.args[2] }),
                    .call_syscall => try w.print("    v{d} = (uint64_t)(-38LL);\n", .{inst.dest}),
                    else => try w.writeAll("    lir_trap();\n"),
                }
            }
        }
        try w.writeAll("    return 0ULL;\n}\n\n");
    }

    const mfi = main_fi orelse return error.MissingMain;
    try w.print(
        \\int main(int argc, char **argv) {{
        \\    lir_g_argc = argc;
        \\    lir_g_argv = argv;
        \\    lir_heap_secret = lir_random_u64() | 1ULL;
        \\    return (int)(int64_t)lir_fn_{d}();
        \\}}
        \\
    , .{mfi});
    _ = target;
    return try out.toOwnedSlice(alloc);
}

fn findZigExe(alloc: std.mem.Allocator) ?[]const u8 {
    if (std.process.getEnvVarOwned(alloc, "LIR_ZIG")) |z| {
        if (z.len > 0) return z;
        alloc.free(z);
    } else |_| {}
    // Check PATH for "zig"
    if (std.process.getEnvVarOwned(alloc, "PATH")) |path_env| {
        defer alloc.free(path_env);
        const sep: u8 = if (@import("builtin").os.tag == .windows) ';' else ':';
        var it = std.mem.splitScalar(u8, path_env, sep);
        while (it.next()) |dir| {
            if (dir.len == 0) continue;
            const exe_name = if (@import("builtin").os.tag == .windows) "zig.exe" else "zig";
            const full = std.fs.path.join(alloc, &.{ dir, exe_name }) catch continue;
            std.fs.cwd().access(full, .{}) catch {
                alloc.free(full);
                continue;
            };
            return full;
        }
    } else |_| {}
    return null;
}

fn findHostCC(alloc: std.mem.Allocator) ?[]const u8 {
    if (std.process.getEnvVarOwned(alloc, "CC")) |cc_env| {
        if (cc_env.len > 0) return cc_env;
        alloc.free(cc_env);
    } else |_| {}
    const path_env = std.process.getEnvVarOwned(alloc, "PATH") catch return null;
    defer alloc.free(path_env);
    const sep: u8 = if (@import("builtin").os.tag == .windows) ';' else ':';
    const candidates = if (@import("builtin").os.tag == .windows)
        [_][]const u8{ "clang.exe", "gcc.exe", "cc.exe" }
    else
        [_][]const u8{ "cc", "clang", "gcc" };
    for (candidates) |cand| {
        var it = std.mem.splitScalar(u8, path_env, sep);
        while (it.next()) |dir| {
            if (dir.len == 0) continue;
            const full = std.fs.path.join(alloc, &.{ dir, cand }) catch continue;
            std.fs.cwd().access(full, .{}) catch {
                alloc.free(full);
                continue;
            };
            return full;
        }
    }
    return null;
}

pub fn compileCWithToolchain(
    alloc: std.mem.Allocator,
    c_source: []const u8,
    target: Target,
    has_net: bool,
    has_threads: bool,
) ![]u8 {
    var tdir_buf: [256]u8 = undefined;
    const tdir = util.getTempDir(&tdir_buf);
    const id = util.randomU64();
    const pid = util.sysGetPid();

    const c_path = try std.fmt.allocPrint(alloc, "{s}/lir_c_{d}_{x}.c", .{ tdir, pid, id });
    defer {
        std.fs.cwd().deleteFile(c_path) catch {};
        alloc.free(c_path);
    }
    const bin_path = try std.fmt.allocPrint(alloc, "{s}/lir_c_{d}_{x}{s}", .{ tdir, pid, id, target.exeSuffix() });
    defer {
        std.fs.cwd().deleteFile(bin_path) catch {};
        alloc.free(bin_path);
    }

    if (!util.writeFileAtomic(c_path, c_source, 0o600)) return error.CCompileFailed;

    var argv = std.ArrayListUnmanaged([]const u8){};
    defer argv.deinit(alloc);

    const zig_exe = findZigExe(alloc);
    defer if (zig_exe) |ze| alloc.free(ze);
    const host_cc = if (zig_exe == null and target.isHost()) findHostCC(alloc) else null;
    defer if (host_cc) |hc| alloc.free(hc);

    if (zig_exe) |ze| {
        try argv.append(alloc, ze);
        try argv.append(alloc, "cc");
        try argv.append(alloc, "-target");
        try argv.append(alloc, target.zigTriple());
    } else if (host_cc) |hc| {
        try argv.append(alloc, hc);
    } else {
        return error.CCompilerNotFound;
    }

    try argv.append(alloc, "-std=c11");
    try argv.append(alloc, "-O2");
    if (target.os != .wasi and target.os != .windows) {
        try argv.append(alloc, "-fstack-protector-strong");
    }
    try argv.append(alloc, "-w");
    try argv.append(alloc, c_path);
    try argv.append(alloc, "-o");
    try argv.append(alloc, bin_path);
    if (target.os != .windows) {
        try argv.append(alloc, "-lm");
        if (has_threads and target.os != .wasi and target.os != .macos) {
            try argv.append(alloc, "-lpthread");
        }
    } else if (has_net) {
        try argv.append(alloc, "-lws2_32");
    }

    const run_res = std.process.Child.run(.{
        .allocator = alloc,
        .argv = argv.items,
    }) catch return error.CCompilerNotFound;
    defer alloc.free(run_res.stdout);
    defer alloc.free(run_res.stderr);

    switch (run_res.term) {
        .Exited => |code| if (code != 0) {
            if (run_res.stderr.len > 0) util.printErr(run_res.stderr);
            return error.CCompileFailed;
        },
        else => return error.CCompileFailed,
    }

    return std.fs.cwd().readFileAlloc(alloc, bin_path, 64 * 1024 * 1024) catch return error.CCompileFailed;
}

pub fn compileToBinary(alloc: std.mem.Allocator, module: *const IRModule, source: []const u8, target: Target) ![]u8 {
    const caps = scanCapabilities(module);
    const c_src = try emitC(alloc, module, source, target);
    defer alloc.free(c_src);
    return compileCWithToolchain(alloc, c_src, target, caps.has_net, caps.has_threads);
}
